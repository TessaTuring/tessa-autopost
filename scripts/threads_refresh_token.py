"""Refresh the Threads long-lived token (valid 60 days) and print the new one.

Meta only allows a refresh once the token is at least 24 hours old and not yet expired.
If the refresh is refused this exits non-zero and the workflow fails loudly, which is the
signal that the token needs to be re-generated by hand.
"""
import os

import requests

r = requests.get(
    "https://graph.threads.net/refresh_access_token",
    params={"grant_type": "th_refresh_token", "access_token": os.environ["THREADS_ACCESS_TOKEN"].strip()},
    timeout=60,
)
if r.status_code >= 400:
    raise SystemExit(f"Threads token refresh failed ({r.status_code}): {r.text}")
print(r.json()["access_token"])
